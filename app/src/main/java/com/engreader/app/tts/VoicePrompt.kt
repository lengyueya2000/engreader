package com.engreader.app.tts

/**
 * The clip a cloning voice is prompted with: what was said, and how it sounded.
 *
 * A zero-shot voice is not a speaker index inside a graph — it is a recording. The
 * engine is handed the samples and, separately, the words those samples say; the
 * alignment between the two is what the clone copies. Hand it a text that does not
 * match the audio and the model still produces speech, but the voice drifts, which
 * is the kind of failure that sounds like "a bit off" rather than like a bug. So the
 * two travel together in one value and are stored side by side on disk.
 *
 * Kept free of Android imports, like [VoiceCatalog], so the parsing can be unit-tested
 * against bytes rather than against a device.
 */
internal data class VoicePrompt(
    /** Mono samples in [-1, 1]. */
    val samples: FloatArray,
    val sampleRate: Int,
    /** Exactly what [samples] says, as the engine will be told. */
    val text: String,
) {
    // FloatArray gives identity equality, which would make two prompts built from the
    // same asset compare unequal. Nothing here is used as a map key today, but a data
    // class that quietly lies about equality is a trap for the next reader.
    override fun equals(other: Any?): Boolean {
        if (this === other) return true
        if (other !is VoicePrompt) return false
        return sampleRate == other.sampleRate &&
            text == other.text &&
            samples.contentEquals(other.samples)
    }

    override fun hashCode(): Int {
        var result = samples.contentHashCode()
        result = 31 * result + sampleRate
        result = 31 * result + text.hashCode()
        return result
    }

    companion object {

        /** Marks the chunk that carries the format, and the one that carries audio. */
        private const val CHUNK_HEADER_BYTES = 8

        /** Enough of `fmt ` to read the tag, channel count, rate and bit depth. */
        private const val FMT_MIN_BYTES = 16

        /** `WAVE_FORMAT_PCM`; the bundled clip is 16-bit little-endian. */
        private const val FORMAT_PCM = 1

        /** `WAVE_FORMAT_IEEE_FLOAT`, which some tools write for the same audio. */
        private const val FORMAT_FLOAT = 3

        /**
         * Parses one RIFF/WAVE payload.
         *
         * Deliberately not a general WAV reader: the clip ships in the APK and is
         * generated by this project, so the only formats accepted are the two a
         * synthesiser or an audio editor actually writes — 16-bit PCM and 32-bit
         * float. Anything else returns null and the voice is reported unavailable,
         * which is better than feeding the engine samples decoded with the wrong
         * width: that produces noise, and noise would be blamed on the model.
         *
         * @return the prompt, or null when [bytes] is not a mono WAV in a format this
         *   understands.
         */
        fun parse(bytes: ByteArray, text: String): VoicePrompt? {
            if (bytes.size < 12 + CHUNK_HEADER_BYTES) return null
            if (!bytes.startsWithAscii(0, "RIFF") || !bytes.startsWithAscii(8, "WAVE")) return null

            var position = 12
            var format: Format? = null
            var data: ByteArray? = null
            while (position + CHUNK_HEADER_BYTES <= bytes.size) {
                val id = bytes.asciiAt(position, 4)
                val size = bytes.intLeAt(position + 4)
                val body = position + CHUNK_HEADER_BYTES
                // A size that runs past the buffer means the file is truncated, and a
                // negative one means it is not a WAV at all. Either way there is
                // nothing trustworthy left to read.
                if (size < 0 || body.toLong() + size > bytes.size) return null
                when (id) {
                    "fmt " -> format = readFormat(bytes, body, size)
                    "data" -> data = bytes.copyOfRange(body, body + size)
                }
                // Chunks are word-aligned: an odd size is followed by a pad byte.
                position = body + size + (size and 1)
            }

            val fmt = format ?: return null
            val payload = data ?: return null
            val samples = decode(payload, fmt) ?: return null
            if (samples.isEmpty()) return null
            return VoicePrompt(samples, fmt.sampleRate, text)
        }

        private class Format(val formatTag: Int, val channels: Int, val sampleRate: Int, val bits: Int)

        private fun readFormat(bytes: ByteArray, offset: Int, size: Int): Format? {
            if (size < FMT_MIN_BYTES) return null
            return Format(
                formatTag = bytes.unsignedShortLeAt(offset),
                channels = bytes.unsignedShortLeAt(offset + 2),
                sampleRate = bytes.intLeAt(offset + 4),
                bits = bytes.unsignedShortLeAt(offset + 14),
            )
        }

        private fun decode(payload: ByteArray, fmt: Format): FloatArray? {
            // Down-mixing would need the channel layout, which the clip does not carry;
            // the bundled prompt is mono and a stereo one is a packaging mistake worth
            // reporting rather than guessing at.
            if (fmt.channels != 1) return null
            if (fmt.sampleRate <= 0) return null
            return when {
                fmt.formatTag == FORMAT_PCM && fmt.bits == 16 ->
                    FloatArray(payload.size / 2) { i ->
                        // Little-endian, signed, scaled by 32768 so -32768 maps to -1.
                        (payload.shortLeAt(i * 2) / 32768.0f)
                    }
                fmt.formatTag == FORMAT_FLOAT && fmt.bits == 32 ->
                    FloatArray(payload.size / 4) { i ->
                        Float.fromBits(payload.intLeAt(i * 4))
                    }
                else -> null
            }
        }

        private fun ByteArray.startsWithAscii(offset: Int, text: String): Boolean =
            asciiAt(offset, text.length) == text

        private fun ByteArray.asciiAt(offset: Int, length: Int): String {
            if (offset < 0 || offset + length > size) return ""
            return String(this, offset, length, Charsets.US_ASCII)
        }

        /**
         * One unsigned 16-bit little-endian field, for the format header.
         *
         * Separate from [shortLeAt] on purpose: the header's fields are counts and
         * flags, where a value above 32767 is meaningful rather than negative, and
         * reusing the signed reader here would turn a stereo channel count into a
         * negative number that then silently fails the mono check.
         */
        private fun ByteArray.unsignedShortLeAt(offset: Int): Int =
            (this[offset].toInt() and 0xFF) or ((this[offset + 1].toInt() and 0xFF) shl 8)

        /**
         * One signed 16-bit little-endian sample.
         *
         * Sign-extended: assembling the two bytes as an unsigned `Int` gives 32768 for
         * the byte pair `00 80`, and dividing that by 32768 yields +1.0 — the loudest
         * possible click, on the samples that were meant to be the quietest. `toShort()`
         * is what puts the sign back.
         */
        private fun ByteArray.shortLeAt(offset: Int): Int =
            (((this[offset].toInt() and 0xFF) or
                ((this[offset + 1].toInt() and 0xFF) shl 8)).toShort()).toInt()

        private fun ByteArray.intLeAt(offset: Int): Int =
            (this[offset].toInt() and 0xFF) or
                ((this[offset + 1].toInt() and 0xFF) shl 8) or
                ((this[offset + 2].toInt() and 0xFF) shl 16) or
                ((this[offset + 3].toInt() and 0xFF) shl 24)
    }
}
