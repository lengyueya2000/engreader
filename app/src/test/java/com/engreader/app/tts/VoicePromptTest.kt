package com.engreader.app.tts

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayOutputStream

/**
 * The reference clip is the one input the clone cannot do without, and a clip decoded
 * with the wrong width produces noise rather than an error — noise that would be
 * blamed on the model. So the parser is pinned against bytes here rather than trusted.
 */
class VoicePromptTest {

    // ------------------------------------------------------------- building WAVs

    private fun intLe(value: Int) = byteArrayOf(
        (value and 0xFF).toByte(),
        ((value shr 8) and 0xFF).toByte(),
        ((value shr 16) and 0xFF).toByte(),
        ((value shr 24) and 0xFF).toByte(),
    )

    private fun shortLe(value: Int) = byteArrayOf(
        (value and 0xFF).toByte(),
        ((value shr 8) and 0xFF).toByte(),
    )

    private inner class WavBuilder(
        private val formatTag: Int = FORMAT_PCM,
        private val channels: Int = 1,
        private val sampleRate: Int = 24000,
        private val bits: Int = 16,
    ) {
        private val chunks = mutableListOf<Pair<String, ByteArray>>()

        fun chunk(id: String, body: ByteArray) = apply { chunks += id to body }

        fun build(): ByteArray {
            val payload = ByteArrayOutputStream()
            payload.write("WAVE".toByteArray(Charsets.US_ASCII))
            chunks.forEach { (id, body) ->
                payload.write(id.toByteArray(Charsets.US_ASCII))
                payload.write(intLe(body.size))
                payload.write(body)
                // Chunks are word-aligned.
                if (body.size % 2 == 1) payload.write(0)
            }
            val body = payload.toByteArray()
            val out = ByteArrayOutputStream()
            out.write("RIFF".toByteArray(Charsets.US_ASCII))
            out.write(intLe(body.size))
            out.write(body)
            return out.toByteArray()
        }

        fun fmt(): ByteArray {
            val body = ByteArrayOutputStream()
            body.write(shortLe(formatTag))
            body.write(shortLe(channels))
            body.write(intLe(sampleRate))
            body.write(intLe(sampleRate * channels * bits / 8)) // byte rate
            body.write(shortLe(channels * bits / 8))            // block align
            body.write(shortLe(bits))
            return body.toByteArray()
        }
    }

    private fun pcm16(samples: IntArray): ByteArray {
        val out = ByteArrayOutputStream()
        samples.forEach { out.write(shortLe(it)) }
        return out.toByteArray()
    }

    /** A 16-bit mono clip, the shape the bundled prompt actually ships in. */
    private fun pcmWav(samples: IntArray, sampleRate: Int = 24000): ByteArray =
        WavBuilder(sampleRate = sampleRate)
            .chunk("fmt ", WavBuilder(sampleRate = sampleRate).fmt())
            .chunk("data", pcm16(samples))
            .build()

    // -------------------------------------------------------------- the happy path

    @Test
    fun `a 16-bit mono clip is decoded to the expected samples`() {
        val wav = pcmWav(intArrayOf(0, 32767, -32768, 16384))
        val prompt = VoicePrompt.parse(wav, "hello there")
        assertNotNull(prompt)
        requireNotNull(prompt)
        assertEquals(24000, prompt.sampleRate)
        assertEquals("hello there", prompt.text)
        assertEquals(4, prompt.samples.size)
        assertEquals(0f, prompt.samples[0], 1e-6f)
        // 32767 / 32768, not exactly 1: the scale is chosen so -32768 maps to -1.
        assertEquals(1f, prompt.samples[1], 1e-4f)
        assertEquals(-1f, prompt.samples[2], 1e-6f)
        assertEquals(0.5f, prompt.samples[3], 1e-6f)
    }

    @Test
    fun `a 32-bit float clip is decoded too`() {
        // Some editors write float WAVs; the prompt is regenerated by this project, so
        // accepting the second format costs a branch and avoids a re-export step.
        val body = ByteArrayOutputStream()
        listOf(0f, 0.5f, -0.25f).forEach { body.write(intLe(java.lang.Float.floatToIntBits(it))) }
        val builder = WavBuilder(formatTag = 3, bits = 32)
        val wav = builder.chunk("fmt ", builder.fmt()).chunk("data", body.toByteArray()).build()
        val prompt = VoicePrompt.parse(wav, "float clip")
        assertNotNull(prompt)
        requireNotNull(prompt)
        assertEquals(3, prompt.samples.size)
        assertEquals(0.5f, prompt.samples[1], 1e-6f)
        assertEquals(-0.25f, prompt.samples[2], 1e-6f)
    }

    @Test
    fun `a chunk before the data chunk is skipped over`() {
        // Real files carry a LIST or fact chunk between fmt and data. Stopping at the
        // first unexpected id would report a perfectly good clip as unreadable.
        val builder = WavBuilder()
        val wav = builder
            .chunk("fmt ", builder.fmt())
            .chunk("LIST", "INFOhello".toByteArray(Charsets.US_ASCII))
            .chunk("data", pcm16(intArrayOf(100, 200)))
            .build()
        val prompt = VoicePrompt.parse(wav, "text")
        assertNotNull(prompt)
        assertEquals(2, requireNotNull(prompt).samples.size)
    }

    @Test
    fun `an odd-sized chunk is skipped with its pad byte`() {
        // Misreading the pad byte shifts every following chunk header by one, which
        // turns the audio into garbage rather than into an error.
        val builder = WavBuilder()
        val wav = builder
            .chunk("fmt ", builder.fmt())
            .chunk("LIST", byteArrayOf(1, 2, 3)) // odd size, one pad byte follows
            .chunk("data", pcm16(intArrayOf(100, 200, 300)))
            .build()
        val prompt = VoicePrompt.parse(wav, "text")
        assertNotNull(prompt)
        assertEquals(3, requireNotNull(prompt).samples.size)
    }

    // ------------------------------------------------------------------ rejections

    @Test
    fun `something that is not a RIFF file is rejected`() {
        assertNull(VoicePrompt.parse("not a wav at all, just text".toByteArray(), "text"))
        assertNull(VoicePrompt.parse(ByteArray(0), "text"))
    }

    @Test
    fun `a file with no data chunk is rejected`() {
        val builder = WavBuilder()
        val wav = builder.chunk("fmt ", builder.fmt()).build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    @Test
    fun `a file with no format chunk is rejected`() {
        val builder = WavBuilder()
        val wav = builder.chunk("data", pcm16(intArrayOf(1, 2))).build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    @Test
    fun `a stereo clip is rejected rather than down-mixed`() {
        // Down-mixing needs the channel layout, which the clip does not carry. A
        // packaging mistake is better reported than guessed at.
        val builder = WavBuilder(channels = 2)
        val wav = builder.chunk("fmt ", builder.fmt())
            .chunk("data", pcm16(intArrayOf(1, 2, 3, 4)))
            .build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    @Test
    fun `an 8-bit clip is rejected rather than decoded as 16-bit`() {
        // The failure this guards: decoding 8-bit bytes as 16-bit pairs produces noise
        // at the right length, so it would sound like a broken model.
        val builder = WavBuilder(bits = 8)
        val wav = builder.chunk("fmt ", builder.fmt())
            .chunk("data", byteArrayOf(1, 2, 3, 4))
            .build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    @Test
    fun `a truncated data chunk is rejected`() {
        // A size that claims more bytes than exist means the file is cut short; the
        // samples past the cut are missing, so the clip is not usable.
        val builder = WavBuilder()
        val good = builder.chunk("fmt ", builder.fmt())
            .chunk("data", pcm16(intArrayOf(1, 2, 3, 4)))
            .build()
        val truncated = good.copyOfRange(0, good.size - 3)
        assertNull(VoicePrompt.parse(truncated, "text"))
    }

    @Test
    fun `an empty data chunk is rejected`() {
        val builder = WavBuilder()
        val wav = builder.chunk("fmt ", builder.fmt())
            .chunk("data", ByteArray(0))
            .build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    @Test
    fun `a zero sample rate is rejected`() {
        val builder = WavBuilder(sampleRate = 0)
        val wav = builder.chunk("fmt ", builder.fmt())
            .chunk("data", pcm16(intArrayOf(1, 2)))
            .build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    @Test
    fun `a short format chunk is rejected`() {
        val builder = WavBuilder()
        val wav = builder.chunk("fmt ", byteArrayOf(1, 0, 1, 0))
            .chunk("data", pcm16(intArrayOf(1, 2)))
            .build()
        assertNull(VoicePrompt.parse(wav, "text"))
    }

    // ------------------------------------------------------------------- equality

    @Test
    fun `two prompts with the same samples are equal`() {
        // FloatArray gives identity equality, so without an override two prompts built
        // from the same asset would compare unequal — a data class that lies about
        // equality is a trap for whoever reads this next.
        val wav = pcmWav(intArrayOf(1, 2, 3))
        val a = VoicePrompt.parse(wav, "same")
        val b = VoicePrompt.parse(wav, "same")
        assertEquals(a, b)
        assertEquals(a.hashCode(), b.hashCode())
    }

    @Test
    fun `prompts differing in text or samples are not equal`() {
        val wav = pcmWav(intArrayOf(1, 2, 3))
        val other = pcmWav(intArrayOf(1, 2, 4))
        val base = VoicePrompt.parse(wav, "same")
        assertTrue(base != VoicePrompt.parse(wav, "different"))
        assertTrue(base != VoicePrompt.parse(other, "same"))
    }

    @Test
    fun `a clip of silence is still a usable prompt`() {
        // Silence is not a parser error — it is a bad recording. The parser's job is
        // to decode what is there; whether the clip is any good is the measurement
        // tool's question, not this one's.
        val prompt = VoicePrompt.parse(pcmWav(IntArray(100)), "silence")
        assertNotNull(prompt)
        assertEquals(100, requireNotNull(prompt).samples.size)
    }

    private companion object {
        const val FORMAT_PCM = 1
    }
}
